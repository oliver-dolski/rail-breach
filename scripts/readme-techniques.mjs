#!/usr/bin/env node
// Writes, or with --check verifies, the technique table in README.md.
//
// The table sits between the two marker lines below and is rendered from
// src/content/attack-ics.json, the catalogue generated from the pinned STIX bundle, so no
// ID, name or tactic in the README is typed by hand. Default mode rewrites the block;
// --check exits 1 with a summary when the block differs from what the catalogue gives.
//
// Usage: node scripts/readme-techniques.mjs [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const START = "<!-- techniques:start -->";
export const END = "<!-- techniques:end -->";

const title = (slug) =>
  slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");

/** attack.mitre.org page of a technique: T0865 -> /techniques/T0865/, T1692.001 -> /techniques/T1692/001/. */
export const techniqueUrl = (id) => `https://attack.mitre.org/techniques/${id.replace(".", "/")}/`;

/** The text between the markers (without the marker lines), rendered from the catalogue. */
export function renderBlock(catalogue) {
  const current = catalogue.techniques
    .filter((t) => !t.revoked)
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const rows = current.map(
    (t) =>
      `| [${t.id}](${techniqueUrl(t.id)}) | ${t.name} | ${t.tactics.map(title).join(", ")} | ${t.legacyId ?? ""} |`,
  );
  return [
    `ATT&CK for ICS ${catalogue.attackVersion}, ${current.length} techniques. Generated by \`npm run readme:techniques\` from \`src/content/attack-ics.json\` (source bundle SHA-256 \`${catalogue.source.sha256}\`). Do not edit by hand.`,
    "",
    "| ID | Name | Tactics | Before v19 |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/** The README with the block between the markers replaced; throws when a marker is missing. */
export function applyBlock(readme, block) {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s === -1 || e === -1 || e < s) {
    throw new Error(`README.md needs the lines ${START} and ${END}, in that order`);
  }
  return `${readme.slice(0, s + START.length)}\n${block}\n${readme.slice(e)}`;
}

/** The block as it stands in the README, without the marker lines. */
export function currentBlock(readme) {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s === -1 || e === -1 || e < s) return null;
  return readme.slice(s + START.length + 1, e - 1);
}

function main(argv) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const catalogue = JSON.parse(readFileSync(join(root, "src/content/attack-ics.json"), "utf8"));
  const path = join(root, "README.md");
  const readme = readFileSync(path, "utf8");
  const block = renderBlock(catalogue);
  const next = applyBlock(readme, block);
  if (argv.includes("--check")) {
    if (next === readme) {
      console.log("readme-techniques: the table matches the catalogue");
      return 0;
    }
    const have = (currentBlock(readme) ?? "").split("\n");
    const want = block.split("\n");
    const differing =
      want.filter((line, i) => line !== have[i]).length + Math.abs(want.length - have.length);
    console.error(
      `readme-techniques: README.md differs from the catalogue (${differing} lines). Run: npm run readme:techniques`,
    );
    return 1;
  }
  if (next !== readme) writeFileSync(path, next);
  console.log(`readme-techniques: wrote ${block.split("\n").length - 4} rows`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
